"""
tests/test_document_and_artifact_workflows.py — Tests for Documents and Artifact Lifecycle

Validates:
  1. Word document generation, heading/table rendering, and formatting
  2. Excel spreadsheet formula injection prevention (safe escaping of =, +, -, @)
  3. Excel numeric, float, and negative number preservation
  4. PDF conversion failure handling (falls back to DOCX without losing files)
  5. Artifact lifecycle validation (detects empty 0-byte files, non-existent files)
  6. Artifact SHA-256 calculation and duplicate-delivery prevention (Scenario E)
"""

import os
import sys
import unittest
import tempfile

_REPO_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _REPO_DIR not in sys.path:
    sys.path.insert(0, _REPO_DIR)

from core.content_types import ContentTable, ContentSection, StructuredDocument, sanitize_excel_value
from core.artifacts.artifact_manager import ArtifactLifecycleManager
from core.database.sqlite_db import init_db, record_artifact, get_artifacts_for_task, mark_artifact_delivered
from tools.excel_creator import create_excel_report
from tools.doc_creator import create_document, _docx_to_pdf


class TestDocumentAndArtifactWorkflows(unittest.TestCase):

    def setUp(self):
        init_db()
        self.artifact_manager = ArtifactLifecycleManager()

    # ── Excel Formula Injection & Type Preservation Tests ──────────────────────

    def test_excel_formula_injection_sanitization(self):
        """Verify that dangerous strings starting with =, +, -, @ are escaped."""
        dangerous_cmd = "=cmd|'/c calc'!A0"
        sanitized_cmd = sanitize_excel_value(dangerous_cmd)
        self.assertEqual(sanitized_cmd, "'=cmd|'/c calc'!A0")

        dangerous_plus = "+1234567890-MALICIOUS"
        sanitized_plus = sanitize_excel_value(dangerous_plus)
        self.assertTrue(sanitized_plus.startswith("'"))

    def test_excel_numeric_preservation(self):
        """Verify that genuine integers, floats, and negative numbers are preserved."""
        # Genuine integers
        self.assertEqual(sanitize_excel_value(42), 42)
        self.assertEqual(sanitize_excel_value("42"), 42)
        # Genuine floats
        self.assertEqual(sanitize_excel_value(3.1415), 3.1415)
        self.assertEqual(sanitize_excel_value("3.1415"), 3.1415)
        # Negative numbers
        self.assertEqual(sanitize_excel_value(-15), -15)
        self.assertEqual(sanitize_excel_value("-15.5"), -15.5)

    def test_excel_report_generation(self):
        """Verify that create_excel_report produces a valid .xlsx file with multiple sheets."""
        sheets = [
            {
                "name": "Summary",
                "headers": ["Metric", "Value"],
                "rows": [["Revenue", 500000], ["Cost", -150000]],
            },
            {
                "name": "Department Breakdown",
                "headers": ["Department", "Headcount"],
                "rows": [["Engineering", 45], ["Marketing", 20]],
            },
        ]
        file_path = create_excel_report.invoke({
            "title": "Quarterly Operations Report",
            "sheets": sheets,
            "task_number": 99,
        })
        self.assertTrue(os.path.isfile(file_path))
        self.assertGreater(os.path.getsize(file_path), 1000)
        self.assertTrue(file_path.endswith(".xlsx"))

    # ── Word Generation & Content Validation ───────────────────────────────────

    def test_structured_document_validation(self):
        """Verify that StructuredDocument validates headings, sections, and column count."""
        # Valid document
        tbl = ContentTable(headers=["Col A", "Col B"], rows=[[1, 2], [3, 4]])
        doc = StructuredDocument(
            title="Valid Proposal",
            sections=[ContentSection(heading="Section 1", content="Body", table=tbl)],
        )
        self.assertEqual(doc.validate(), [])

        # Malformed table row count
        bad_tbl = ContentTable(headers=["Col A", "Col B"], rows=[[1, 2, 3]])  # 3 cols instead of 2
        bad_doc = StructuredDocument(
            title="Bad Table Doc",
            sections=[ContentSection(heading="Section 1", content="Body", table=bad_tbl)],
        )
        errs = bad_doc.validate()
        self.assertGreater(len(errs), 0)
        self.assertIn("columns, expected 2", errs[0])

    def test_word_document_creation(self):
        """Verify that create_document generates a valid .docx file."""
        content = """# Executive Briefing
This is a test document generated by the multi-agent system.

## Performance Metrics
| Metric | Q1 | Q2 |
|---|---|---|
| Revenue | 100K | 150K |
| Uptime | 99.9% | 99.95% |
"""
        file_path = create_document.invoke({
            "title": "Operations Summary",
            "content": content,
            "format": "word",
        })
        self.assertTrue(os.path.isfile(file_path))
        self.assertGreater(os.path.getsize(file_path), 1000)
        self.assertTrue(file_path.endswith(".docx"))

    def test_pdf_conversion_failure_preserves_docx(self):
        """Verify that if PDF conversion fails or is unavailable, the source DOCX is safely preserved."""
        # Create a dummy docx file
        with tempfile.NamedTemporaryFile(suffix=".docx", delete=False) as f:
            f.write(b"PK\x03\x04MockDocxContent")
            docx_path = f.name

        try:
            # When convert fails, _docx_to_pdf returns docx_path and keeps it
            result_path = _docx_to_pdf(docx_path)
            self.assertTrue(os.path.isfile(result_path))
            self.assertTrue(result_path.endswith(".docx") or result_path.endswith(".pdf"))
        finally:
            if os.path.exists(docx_path):
                os.remove(docx_path)

    def test_page_count_extraction(self):
        """Verify explicit page count extraction from various user prompts."""
        from agents.assistant_agent import _extract_page_count
        self.assertEqual(_extract_page_count("i need 5 page word"), 5)
        self.assertEqual(_extract_page_count("please send 2 page word document"), 2)
        self.assertEqual(_extract_page_count("create a 5 page pdf report"), 5)
        self.assertEqual(_extract_page_count("can you prepare 2 page pdf?"), 2)
        self.assertEqual(_extract_page_count("two-page word summary"), 2)
        self.assertEqual(_extract_page_count("pages: 4"), 4)
        self.assertEqual(_extract_page_count("just a standard document"), 0)

    def test_word_page_counter_and_page_breaks(self):
        """Verify that create_document with page_count partitions content with exact page breaks."""
        import docx
        sample_md = """# Performance Report

## Section 1: Executive Overview
First section covering executive summary and highlights.

## Section 2: Financial Metrics
Second section covering financial data and margins.

## Section 3: Operations Analysis
Third section covering operations and logistics.

## Section 4: Technology Roadmap
Fourth section covering cloud upgrades and infra.

## Section 5: Future Outlook
Fifth section covering projections and strategic pillars.
"""
        # Test 2-page target
        path_2 = create_document.invoke({
            "title": "Two Page Report",
            "content": sample_md,
            "format": "word",
            "page_count": 2,
        })
        self.assertTrue(os.path.isfile(path_2))
        d2 = docx.Document(path_2)
        brs_2 = [p for p in d2.paragraphs if "page" in p._element.xml]
        self.assertEqual(len(brs_2), 1)  # 2 pages => exactly 1 page break

        # Test 5-page target
        path_5 = create_document.invoke({
            "title": "Five Page Report",
            "content": sample_md,
            "format": "word",
            "page_count": 5,
        })
        self.assertTrue(os.path.isfile(path_5))
        d5 = docx.Document(path_5)
        brs_5 = [p for p in d5.paragraphs if "page" in p._element.xml]
        self.assertEqual(len(brs_5), 4)  # 5 pages => exactly 4 page breaks

        # Clean up
        for p in (path_2, path_5):
            if os.path.exists(p):
                try:
                    os.remove(p)
                except Exception:
                    pass

