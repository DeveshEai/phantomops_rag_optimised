from email.mime.text import MIMEText
from email.mime.base import MIMEBase
from email import encoders

from core.config import GMAIL_TOKEN_PATH

# Read + send + modify (mark read) + create calendar events. One OAuth token
# covers both Gmail and Google Calendar so a single sign-in authorises everything.
GMAIL_SCOPES = [
    "https://www.googleapis.com/auth/gmail.readonly",
    "https://www.googleapis.com/auth/gmail.send",
    "https://www.googleapis.com/auth/gmail.modify",
    "https://www.googleapis.com/auth/calendar.events",
]


# ── Service / Auth ────────────────────────────────────────────────────────────

def get_gmail_service():
    """Build an authenticated Gmail API service from the saved token."""
    from google.oauth2.credentials import Credentials
    from google.auth.transport.requests import Request
    from googleapiclient.discovery import build

    if not os.path.isfile(GMAIL_TOKEN_PATH):
        raise RuntimeError(
            f"Gmail token not found at {GMAIL_TOKEN_PATH}. "
            "Run setup_gmail_oauth.py to authenticate."
        )

    creds = Credentials.from_authorized_user_file(GMAIL_TOKEN_PATH, GMAIL_SCOPES)
    if not creds.valid:
        if creds.expired and creds.refresh_token:
            creds.refresh(Request())
            with open(GMAIL_TOKEN_PATH, "w", encoding="utf-8") as f:
                f.write(creds.to_json())
        else:
            raise RuntimeError("Gmail token invalid/expired — re-run setup_gmail_oauth.py.")

    return build("gmail", "v1", credentials=creds, cache_discovery=False)


def get_calendar_service():
    """Build an authenticated Google Calendar service from the same OAuth token."""
    from google.oauth2.credentials import Credentials
    from google.auth.transport.requests import Request
    from googleapiclient.discovery import build

    if not os.path.isfile(GMAIL_TOKEN_PATH):
        raise RuntimeError(
            f"Gmail/Calendar token not found at {GMAIL_TOKEN_PATH}. "
            "Run setup_gmail_oauth.py to authenticate."
        )

    creds = Credentials.from_authorized_user_file(GMAIL_TOKEN_PATH, GMAIL_SCOPES)
    if not creds.valid:
        if creds.expired and creds.refresh_token:
            creds.refresh(Request())
            with open(GMAIL_TOKEN_PATH, "w", encoding="utf-8") as f:
                f.write(creds.to_json())
        else:
            raise RuntimeError(
                "Google token invalid/expired or missing the calendar scope — "
                "re-run setup_gmail_oauth.py to grant calendar access."
            )

    return build("calendar", "v3", credentials=creds, cache_discovery=False)


# ── Message wrapper ───────────────────────────────────────────────────────────

class GmailMessage:
    """Lightweight wrapper exposing the attributes the rest of Sally expects."""

    def __init__(self, service, gmail_id: str, thread_id: str = "", raw: dict = None):
        self.service    = service
        self.object_id  = gmail_id      # Gmail message id (used as message_id_header)
        self.thread_id  = thread_id
        self._raw       = raw

    @property
    def raw(self) -> dict:
        if self._raw is None:
            self._raw = self.service.users().messages().get(
                userId="me", id=self.object_id, format="full"
            ).execute()
            self.thread_id = self._raw.get("threadId", self.thread_id)
        return self._raw

    @property
    def has_attachments(self) -> bool:
        # NOTE: _iter_attachment_parts is a generator — a generator object is always
        # truthy, so we must check whether it actually yields a part, not bool() it.
        return next(_iter_attachment_parts(self.raw.get("payload", {})), None) is not None


# ── Helpers ───────────────────────────────────────────────────────────────────

def _header(payload: dict, name: str) -> str:
    for h in payload.get("headers", []):
        if h.get("name", "").lower() == name.lower():
            return h.get("value", "")
    return ""


def _decode_b64url(data: str) -> bytes:
    return base64.urlsafe_b64decode(data.encode("utf-8")) if data else b""


def _walk_parts(payload: dict):
    """Yield every part in the MIME tree (depth-first)."""
    yield payload
    for part in payload.get("parts", []) or []:
        yield from _walk_parts(part)


def _extract_bodies(payload: dict) -> tuple[str, str]:
    """Return (plain_text, html) from the message payload."""
    plain, html = "", ""
    for part in _walk_parts(payload):
        mime = part.get("mimeType", "")
        body = part.get("body", {})
        data = body.get("data")
        if not data:
            continue
        if mime == "text/plain" and not plain:
            plain = _decode_b64url(data).decode("utf-8", errors="replace")
        elif mime == "text/html" and not html:
            html = _decode_b64url(data).decode("utf-8", errors="replace")
    return plain, html


# Mobile/desktop app footers that add noise to the body (case-insensitive).
_FOOTER_PATTERNS = [
    r"^get outlook for (android|ios).*$",
    r"^sent from my (iphone|ipad|android|samsung|galaxy|huawei|phone|mobile device).*$",
    r"^sent from mail for windows.*$",
    r"^sent from outlook.*$",
    r"^get the outlook app.*$",
]


def _strip_footers(text: str) -> str:
    """Remove auto-appended app signatures (Get Outlook for Android, Sent from my iPhone…)."""
    if not text:
        return ""
    kept = []
    for ln in text.split("\n"):
        if any(re.match(p, ln.strip(), re.IGNORECASE) for p in _FOOTER_PATTERNS):
            continue
        kept.append(ln)
    return "\n".join(kept).strip()


def _split_quoted(text: str) -> tuple[str, str]:
    """Split an email body into (new_text, quoted_thread).

    The NEW text is what the sender just wrote — the only part used for
    decisions (output-type detection, routing, intent). The QUOTED thread is
    kept separately as conversation context (who said what earlier) and to
    detect whether the sender hit reply on the agent's own email.

    Handles Gmail quotes ("On <date> <person> wrote:" + '>' lines) AND Outlook
    desktop/mobile quotes (a line of underscores or "-----Original Message-----"
    followed by a From:/Sent:/To:/Subject: header block). Replies sent from
    Outlook clients into the Gmail mailbox previously leaked the whole quoted
    thread into the body, polluting output-type detection and the LLM context.
    """
    if not text:
        return "", ""
    lines = text.replace("\r\n", "\n").split("\n")
    out = []
    quoted_from = None
    for i, ln in enumerate(lines):
        s = ln.strip()
        # Gmail quote marker: "On <date> <person> wrote:" then '>'-prefixed lines
        if re.match(r"^On .+wrote:\s*$", s):
            quoted_from = i
            break
        # Outlook separators: "________..." rule or classic Original Message banner;
        # plus forwarded-message markers (Outlook/Gmail "Forwarded message",
        # Apple Mail "Begin forwarded message:").
        if (re.match(r"^_{10,}\s*$", s)
                or re.match(r"^-+\s*Original Message\s*-+$", s, re.IGNORECASE)
                or re.match(r"^-+\s*Forwarded message\s*-+$", s, re.IGNORECASE)
                or re.match(r"^Begin forwarded message:\s*$", s, re.IGNORECASE)):
            quoted_from = i
            break
        # Outlook header block without a separator: a "From:" line followed
        # within the next few lines by Sent:/Date:/To:/Subject:
        if re.match(r"^From:\s*\S", s):
            lookahead = " ".join(l.strip() for l in lines[i + 1:i + 4])
            if re.search(r"^(Sent|Date|To|Subject):", lookahead) or \
               re.search(r"\b(Sent|Date|To|Subject):\s", lookahead):
                quoted_from = i
                break
        if s.startswith(">"):
            if quoted_from is None:
                quoted_from = i
            continue
        out.append(ln)
    quoted = "\n".join(lines[quoted_from:]).strip() if quoted_from is not None else ""
    return _strip_footers("\n".join(out)).strip(), quoted


def _strip_quoted(text: str) -> str:
    """Keep only the new reply text (see _split_quoted)."""
    return _split_quoted(text)[0]


def _is_inline_part(part: dict) -> bool:
    """True for inline content (e.g. signature logos, embedded images)."""
    for h in part.get("headers", []):
        name = h.get("name", "").lower()
        val  = h.get("value", "").lower()
        if name == "content-disposition" and val.strip().startswith("inline"):
            return True
        if name == "content-id":          # referenced inline via cid: in HTML
            return True
    return False


def _iter_attachment_parts(payload: dict):
    """Yield parts that are real (non-inline) downloadable attachments."""
    for part in _walk_parts(payload):
        filename = part.get("filename") or ""
        body     = part.get("body", {})
        if filename and (body.get("attachmentId") or body.get("data")):
            if _is_inline_part(part):
                continue   # skip signature logos / embedded images
            yield part


# ── Reading ───────────────────────────────────────────────────────────────────

def list_unread_messages(service, limit: int = 50) -> list:
    """Return unread inbox messages as GmailMessage wrappers, OLDEST first.

    Paginates so a backlog that built up while Sally was offline is fully retrieved
    (up to `limit`), then reverses Gmail's newest-first ordering so emails are
    processed in the order they were received — tasks stay sequential and no
    downtime mail is dropped.
    """
    collected = []
    page_token = None
    while len(collected) < limit:
        resp = service.users().messages().list(
            userId="me", labelIds=["INBOX", "UNREAD"],
            maxResults=min(100, limit - len(collected)), pageToken=page_token,
        ).execute()
        collected.extend(resp.get("messages", []) or [])
        page_token = resp.get("nextPageToken")
        if not page_token:
            break
    # Gmail lists newest-first → reverse for oldest-first processing
    return [GmailMessage(service, m["id"], m.get("threadId", ""))
            for m in reversed(collected)]


def list_messages_since(service, since_epoch: int, limit: int = 50) -> list:
    """Return INBOX messages received at/after `since_epoch` (read OR unread), OLDEST first.

    Used for downtime recovery: unlike the unread filter, this catches mail that
    arrived while Sally was offline even if someone has since opened it. Dedup at
    the caller (draft_exists_for_message) prevents re-replying to handled mail.
    """
    # Gmail's `after:` is exclusive at second granularity, and the watermark is
    # second-precision — so query one second earlier to avoid missing a message
    # that arrived in the SAME second as the watermark. The boundary message is
    # re-fetched but de-duplicated by the caller (draft_exists / seen_ids).
    q = f"in:inbox after:{max(0, int(since_epoch) - 1)}"
    collected = []
    page_token = None
    while len(collected) < limit:
        resp = service.users().messages().list(
            userId="me", q=q,
            maxResults=min(100, limit - len(collected)), pageToken=page_token,
        ).execute()
        collected.extend(resp.get("messages", []) or [])
        page_token = resp.get("nextPageToken")
        if not page_token:
            break
    return [GmailMessage(service, m["id"], m.get("threadId", ""))
            for m in reversed(collected)]


def get_message_detail(msg: GmailMessage) -> dict:
    """Extract the same fields Outlook's get_message_detail returns."""
    payload = msg.raw.get("payload", {})
    plain, html = _extract_bodies(payload)
    body_raw = html or plain
    body, body_quoted = _split_quoted(plain)
    body = body or plain

    sender_raw = _header(payload, "From")
    # Extract bare email from "Name <email@x.com>"
    m = re.search(r"<([^>]+)>", sender_raw)
    sender = (m.group(1) if m else sender_raw).strip()

    def _emails(hdr):
        return [a.lower() for a in re.findall(r"[\w.+-]+@[\w-]+\.[\w.-]+", _header(payload, hdr))]

    return {
        "id":                msg.object_id,
        "thread_id":         msg.raw.get("threadId", ""),   # Gmail thread id
        "sender":            sender or "(unknown)",
        "subject":           _header(payload, "Subject") or "(no subject)",
        "body":              body.strip(),
        "body_raw":          body_raw or "",
        "body_quoted":       body_quoted,                   # quoted thread (context only)
        "message_id_header": msg.object_id,                 # Gmail message id (stable)
        "references":        _header(payload, "References"),
        "received_ts":       int(msg.raw.get("internalDate", "0") or 0) // 1000,  # epoch seconds (UTC)
        "to":                _emails("To"),
        "cc":                _emails("Cc"),
    }


def get_account_address(service) -> str:
    """The Gmail mailbox's own address (used for To/Cc role detection)."""
    try:
        return service.users().getProfile(userId="me").execute().get("emailAddress", "").lower()
    except Exception:
        return ""


def get_message_by_id(service, msg_id: str) -> GmailMessage:
    """Fetch a specific message so we can reply to it."""
    try:
        return GmailMessage(service, msg_id)
    except Exception:
        return None


def has_real_attachment(msg: GmailMessage) -> bool:
    """True if the message has a real (non-inline) attachment. Gmail's
    has_attachments already excludes inline images (signature logos), so this is
    equivalent — provided for parity with the Outlook client."""
    return msg.has_attachments


def get_unsupported_attachment_names(msg: GmailMessage) -> list:
    from tools.file_reader import SUPPORTED_EXTENSIONS
    names = []
    for part in _iter_attachment_parts(msg.raw.get("payload", {})):
        name = part.get("filename", "")
        ext  = os.path.splitext(name)[1].lower()
        if ext and ext not in SUPPORTED_EXTENSIONS:
            names.append(name)
    return names


def download_attachments(msg: GmailMessage, save_dir: str) -> list:
    """Download supported attachments to save_dir. Returns saved file paths."""
    from tools.file_reader import SUPPORTED_EXTENSIONS
    os.makedirs(save_dir, exist_ok=True)
    paths = []
    _MAX = 25 * 1024 * 1024

    def _unique(name: str) -> str:
        safe = (name or "attachment").replace("/", "-").replace("\\", "-").strip() or "attachment"
        base, ext = os.path.splitext(safe)
        dest, n = os.path.join(save_dir, safe), 1
        while os.path.exists(dest):
            dest = os.path.join(save_dir, f"{base}_{n}{ext}")
            n += 1
        return dest

    for part in _iter_attachment_parts(msg.raw.get("payload", {})):
        name = part.get("filename", "")
        ext  = os.path.splitext(name)[1].lower()
        if ext not in SUPPORTED_EXTENSIONS:
            print(f"[Attachment] Skipping unsupported type: {name}")
            continue
        body = part.get("body", {})
        try:
            if body.get("data"):
                content = _decode_b64url(body["data"])
            else:
                att = msg.service.users().messages().attachments().get(
                    userId="me", messageId=msg.object_id, id=body["attachmentId"]
                ).execute()
                content = _decode_b64url(att.get("data", ""))
            if not content or len(content) > _MAX:
                print(f"[Attachment] Skipped {name}: empty or over 25 MB")
                continue
            dest = _unique(name)
            with open(dest, "wb") as f:
                f.write(content)
            paths.append(dest)
            print(f"[Attachment] Saved: {os.path.basename(dest)} ({len(content)} bytes)")
        except Exception as e:
            print(f"[Attachment] Download failed for {name}: {e}")
    return paths


def download_thread_attachments(service, thread_id: str, save_dir: str,
                                exclude_id: str = None, limit: int = 25) -> list:
    """Download supported attachments from the MOST RECENT earlier message in the
    same Gmail thread that has any. Used when the current email references a file
    that wasn't attached to this reply itself.

    Only finds messages in THIS mailbox — works when the agent was on the earlier
    thread messages (e.g. CC'd throughout); it cannot reach a message the agent
    never received.
    """
    if not thread_id:
        return []
    try:
        thread = service.users().threads().get(
            userId="me", id=thread_id, format="metadata").execute()
        msg_ids = [m.get("id") for m in thread.get("messages", []) if m.get("id")]
    except Exception as e:
        print(f"[Gmail] Thread attachment lookup failed: {e}")
        return []
    for mid in reversed(msg_ids[-limit:]):   # most recent first
        if exclude_id and mid == exclude_id:
            continue
        try:
            gm = get_message_by_id(service, mid)
            got = download_attachments(gm, save_dir)
            if got:
                print(f"[Gmail] Pulled {len(got)} attachment(s) from an earlier message in the thread.")
                return got
        except Exception as e:
            print(f"[Gmail] Could not download an earlier thread attachment: {e}")
    return []


def was_reply_already_sent(service, thread_id: str, after_epoch: int = 0) -> bool:
    """Best-effort: True if a reply for this thread is ALREADY in SENT.

    Crash-recovery reconciliation (mirror of the Outlook helper): before resending
    a saved draft on restart, ask Gmail whether a message in this thread carrying
    the SENT label was sent AT/AFTER the inbound email's time. Scopes to THIS
    inbound via `after_epoch` so an earlier reply in the same thread doesn't count.
    Returns False on any error (caller resends the saved draft — never worse)."""
    if not thread_id:
        return False
    try:
        thread = service.users().threads().get(
            userId="me", id=thread_id, format="metadata").execute()
        cutoff_ms = int(after_epoch) * 1000 if after_epoch else 0
        for m in thread.get("messages", []):
            if "SENT" not in (m.get("labelIds") or []):
                continue
            if not cutoff_ms:
                return True
            try:
                if int(m.get("internalDate", "0")) >= cutoff_ms:
                    return True
            except (TypeError, ValueError):
                return True
        return False
    except Exception as e:
        print(f"[Gmail] Sent reconcile check failed ({e}) — assuming not sent.")
        return False


# ── Label Management (for email routing) ─────────────────────────────────────

# In-memory cache so we only call the Labels API once per label name per session.
_label_cache: dict[str, str] = {}


def get_or_create_label(service, label_name: str) -> str:
    """Find or create a Gmail label by name. Returns the label ID.

    Caches results in memory so repeated calls for the same label don't
    hit the API again.
    """
    key = label_name.lower()
    if key in _label_cache:
        return _label_cache[key]

    try:
        resp = service.users().labels().list(userId="me").execute()
        for lbl in resp.get("labels", []):
            if lbl.get("name", "").lower() == key:
                _label_cache[key] = lbl["id"]
                return lbl["id"]
    except Exception as e:
        print(f"[Gmail] Failed to list labels: {e}")

    # Label doesn't exist — create it
    try:
        body = {
            "name": label_name,
            "labelListVisibility": "labelShow",
            "messageListVisibility": "show",
        }
        created = service.users().labels().create(userId="me", body=body).execute()
        lid = created["id"]
        _label_cache[key] = lid
        print(f"[Gmail] Created label '{label_name}' (id={lid})")
        return lid
    except Exception as e:
        print(f"[Gmail] Failed to create label '{label_name}': {e}")
        return ""


def apply_label_and_archive(msg: GmailMessage, label_id: str):
    """Apply a label to the message and remove it from INBOX (archive it)."""
    if not label_id:
        return
    try:
        msg.service.users().messages().modify(
            userId="me", id=msg.object_id,
            body={
                "addLabelIds": [label_id],
                "removeLabelIds": ["INBOX", "UNREAD"],
            }
        ).execute()
        print(f"[Gmail] Labelled and archived message {msg.object_id}")
    except Exception as e:
        print(f"[Gmail] Failed to label message {msg.object_id}: {e}")
        raise  # caller must not advance the watermark past an unfiled email


# ── Writing ───────────────────────────────────────────────────────────────────

def mark_as_read(msg: GmailMessage):
    """Remove the UNREAD label so Sally doesn't reprocess it."""
    try:
        msg.service.users().messages().modify(
            userId="me", id=msg.object_id, body={"removeLabelIds": ["UNREAD"]}
        ).execute()
    except Exception as e:
        print(f"[WARNING] Gmail mark_as_read failed for {msg.object_id}: {e}")


def send_reply(msg: GmailMessage, body: str, attachments: list = None, cc: list = None):
    """Send a threaded reply in the same Gmail conversation.

    Args:
        cc: Optional list of email addresses to CC on the reply.
            Used for reply-all when Sally is CC'd on a thread.
    """
    from skills.email_skill.html_formatter import format_reply_html

    payload      = msg.raw.get("payload", {})
    to_addr      = _header(payload, "From")
    subject      = _header(payload, "Subject") or ""
    orig_msg_id  = _header(payload, "Message-ID")
    references   = _header(payload, "References")
    thread_id    = msg.raw.get("threadId", "")

    if subject and not subject.lower().startswith("re:"):
        subject = "Re: " + subject

    mime = MIMEMultipart("mixed")
    mime["To"]      = to_addr
    if cc:
        mime["Cc"] = ", ".join(cc)
    mime["Subject"] = subject
    if orig_msg_id:
        mime["In-Reply-To"] = orig_msg_id
        mime["References"]   = (references + " " + orig_msg_id).strip()

    mime.attach(MIMEText(format_reply_html(body), "html", "utf-8"))

    for path in attachments or []:
        if not os.path.isfile(path):
            print(f"[Email] Reply attachment missing, skipping: {path}")
            continue
        ctype, _ = mimetypes.guess_type(path)
        maintype, subtype = (ctype or "application/octet-stream").split("/", 1)
        with open(path, "rb") as f:
            part = MIMEBase(maintype, subtype)
            part.set_payload(f.read())
        encoders.encode_base64(part)
        part.add_header("Content-Disposition", "attachment",
                        filename=os.path.basename(path))
        mime.attach(part)
        print(f"[Email] Attached reply file: {path}")

    raw = base64.urlsafe_b64encode(mime.as_bytes()).decode("utf-8")
    send_body = {"raw": raw}
    if thread_id:
        send_body["threadId"] = thread_id

    result = msg.service.users().messages().send(userId="me", body=send_body).execute()
    if not result or not result.get("id"):
        raise RuntimeError("Gmail send failed — no message id returned.")
