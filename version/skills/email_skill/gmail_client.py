"""
skills/email_skill/gmail_client.py — Gmail backend (Gmail API + OAuth)

Mirrors the public interface of outlook_client.py so the email skill can use
either provider interchangeably (selected via EMAIL_PROVIDER in .env).

Functions:
    get_gmail_service()                  -> Gmail API service
    list_unread_messages(service)        -> [GmailMessage]
    get_message_detail(msg)              -> dict (same keys as Outlook)
    get_message_by_id(service, msg_id)   -> GmailMessage
    download_attachments(msg, save_dir)  -> [paths]
    get_unsupported_attachment_names(msg)-> [names]
    send_reply(msg, body, attachments)   -> sends threaded reply
    mark_as_read(msg)                    -> removes UNREAD label

Auth: OAuth via gmail_token.json (generated by setup_gmail_oauth.py).
"""

import os
import re
import base64
import mimetypes
